//! Prints a regenerated `src/commonstring.rs` (from the embedded TPK common string table)
//! to stdout. Run via `just update-commonstring`.

use rabex::UnityVersion;
use rabex::tpk::TpkTypeTreeBlob;
use std::collections::BTreeMap;

const HEADER: &str = r#"//! @generated by `just update-commonstring` from the embedded TPK — do not edit by hand.

use std::collections::BTreeMap;
use std::io;
use std::sync::LazyLock;

use crate::UnityVersion;

/// The common string table for each unity version of the embedded tpk, skipping unchanged versions.
static COMMONSTRING: &[(&str, &[(u32, &str)])] = &[
"#;

const FOOTER: &str = r#"];

static TABLES: LazyLock<Vec<(UnityVersion, BTreeMap<u32, &'static str>)>> = LazyLock::new(|| {
    COMMONSTRING
        .iter()
        .map(|(version, entries)| {
            (
                version.parse().expect("generated version parses"),
                entries.iter().copied().collect(),
            )
        })
        .collect()
});

pub fn common_string_table(target: &UnityVersion) -> Result<&'static BTreeMap<u32, &'static str>, std::io::Error> {
    TABLES
        .iter()
        .rev()
        .find(|(version, _)| target >= version)
        .map(|(_, table)| table)
        .ok_or_else(|| {
            std::io::Error::new(
                io::ErrorKind::InvalidData,
                format!("no common string table at or below {target}"),
            )
        })
}
"#;

fn main() {
    let tpk = TpkTypeTreeBlob::embedded();
    let mut per_version: Vec<(UnityVersion, BTreeMap<u32, &str>)> = tpk
        .common_string
        .version_information
        .iter()
        .map(|(version, entries)| {
            (
                version.clone(),
                entries
                    .iter()
                    .map(|entry| {
                        (
                            entry.offset as u32,
                            tpk.string_buffer[entry.string as usize].as_str(),
                        )
                    })
                    .collect(),
            )
        })
        .collect();
    per_version.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap());

    print!("{HEADER}");
    let mut previous: Option<&BTreeMap<u32, &str>> = None;
    for (version, table) in &per_version {
        if previous == Some(table) {
            continue;
        }
        println!("    (\"{version}\", &[");
        for (offset, s) in table {
            println!("        ({offset}, {s:?}),");
        }
        println!("    ]),");
        previous = Some(table);
    }
    print!("{FOOTER}");
}
